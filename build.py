#!/usr/bin/env python3
"""Build the blackball static blog.

Usage:
    python build.py
    python build.py --serve [--port 8000]

The only dependency is Markdown; see requirements.txt.
"""

from __future__ import annotations

import argparse
import html
import json
import re
import sys
import time
from dataclasses import dataclass
from datetime import date as Date
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from typing import Any

try:
    import markdown
except ImportError:
    print(
        "error: missing build dependency Markdown.\n"
        "install it with: python -m pip install -r requirements.txt",
        file=sys.stderr,
    )
    raise SystemExit(1)


ROOT = Path(__file__).resolve().parent
POSTS_DIR = ROOT / "posts"
TEMPLATES_DIR = ROOT / "templates"
HTML_DIR = ROOT / "html"
SITE_FILE = ROOT / "site.json"

GENERATED_MARKER = "<!-- generated by build.py; edit posts/ or templates/ instead -->"
POST_FILENAME_RE = re.compile(
    r"^(?P<year>\d{4,5})-(?P<month>\d{2})-(?P<day>\d{2})-(?P<slug>.+)\.md$"
)
FRONT_MATTER_RE = re.compile(r"\A---[ \t]*\r?\n(.*?)\r?\n---[ \t]*\r?\n", re.S)
PLACEHOLDER_RE = re.compile(r"{{\s*([a-zA-Z0-9_]+)\s*}}")
HTML_TAG_RE = re.compile(r"<[^>]+>")
SPACE_RE = re.compile(r"\s+")
FENCE_RE = re.compile(r"^[ \t]*(```|~~~).*?^[ \t]*\1[ \t]*$", re.M | re.S)


class BuildError(Exception):
    """A problem with the site content or configuration."""


@dataclass
class Post:
    source: Path
    stem: str
    slug: str
    published: Date
    title: str
    summary: str
    content: str
    author: str = ""
    year: str = ""

    @property
    def url(self) -> str:
        return f"html/{self.stem}.html"

    @property
    def output_name(self) -> str:
        return f"{self.stem}.html"

    @property
    def date_display(self) -> str:
        return f"{self.published.year:04d}.{self.published.month:02d}.{self.published.day:02d}"

    @property
    def byline(self) -> str:
        if self.author and self.year:
            return f"{self.author} · {self.year}"
        if self.author:
            return self.author
        if self.year:
            return self.year
        return self.date_display


def relative(path: Path) -> str:
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def write_file(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def escape(value: Any, *, quote: bool = True) -> str:
    return html.escape(str(value), quote=quote)


def plain_text(value: str) -> str:
    value = re.sub(r"<(script|style)\b.*?</\1>", "", value, flags=re.S | re.I)
    value = HTML_TAG_RE.sub("", value)
    value = html.unescape(value)
    return SPACE_RE.sub(" ", value).strip()


def markdown_text(fragment: str) -> str:
    if not fragment.strip():
        return ""
    rendered = markdown.markdown(fragment, extensions=["extra"])
    return plain_text(rendered)


def shorten(text: str, limit: int = 132) -> str:
    text = text.strip()
    if len(text) <= limit:
        return text
    clipped = text[:limit]
    for punctuation in ("。", "！", "？", "；", "…"):
        cut = clipped.rfind(punctuation)
        if cut >= limit // 2:
            return clipped[: cut + 1]
    return clipped.rstrip("，、；：,;: ") + "…"


def parse_front_matter(source: str, path: Path) -> tuple[dict[str, str], str]:
    """Read optional author/year metadata from a leading --- block."""
    match = FRONT_MATTER_RE.match(source)
    if not match:
        return {}, source

    metadata: dict[str, str] = {}
    for number, line in enumerate(match.group(1).splitlines(), start=2):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if ":" not in line:
            raise BuildError(
                f"{relative(path)}: front matter line {number} must look like 'key: value'"
            )
        key, value = line.split(":", 1)
        key = key.strip()
        value = value.strip().strip('"').strip("'")
        if key not in {"author", "year"}:
            raise BuildError(
                f"{relative(path)}: unsupported front matter key '{key}'"
            )
        metadata[key] = value

    return metadata, source[match.end() :]


def extract_title(source: str, path: Path) -> tuple[str, str]:
    lines = source.splitlines()
    for index, line in enumerate(lines):
        match = re.match(r"^##[ \t]+(.+?)\s*$", line)
        if not match:
            continue
        raw_title = re.sub(r"[ \t]+#+[ \t]*$", "", match.group(1)).strip()
        title = markdown_text(raw_title)
        if not title:
            raise BuildError(f"{relative(path)}: the title after '##' is empty")
        body = "\n".join(lines[:index] + lines[index + 1 :]).strip()
        return title, body
    raise BuildError(
        f"{relative(path)}: no title found. Add a line such as '## 文章标题'."
    )


def extract_summary(body: str) -> str:
    without_code = FENCE_RE.sub("", body)
    for block in re.split(r"\n[ \t]*\n", without_code):
        block = block.strip()
        if not block:
            continue
        if re.match(r"^(#{1,6}\s|```|~~~|\||>|!\[|<|[-*+]\s|\d+[.)]\s)", block):
            continue
        text = markdown_text(block)
        if text:
            return shorten(text)
    return ""


def load_config() -> dict[str, Any]:
    if not SITE_FILE.is_file():
        raise BuildError("site.json is missing")
    try:
        config = json.loads(SITE_FILE.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise BuildError(
            f"site.json: invalid JSON on line {exc.lineno}: {exc.msg}"
        ) from exc
    if not isinstance(config, dict):
        raise BuildError("site.json: the top level must be an object")

    required = (
        "title",
        "tagline",
        "description",
        "author",
        "url",
        "language",
    )
    missing = [key for key in required if key not in config]
    if missing:
        raise BuildError("site.json: missing required field(s): " + ", ".join(missing))
    if not str(config["url"]).startswith(("http://", "https://")):
        raise BuildError("site.json: url must start with http:// or https://")
    config["url"] = str(config["url"]).rstrip("/")
    config.setdefault("logo", "imgs/logo.png")
    config.setdefault("not_found_title", "这条路径不存在。")
    config.setdefault("not_found_body", "页面可能已经被移走，或者还没有被写下。")
    return config


def load_post(path: Path, fallback_summary: str) -> Post:
    try:
        source = path.read_text(encoding="utf-8-sig")
    except UnicodeDecodeError as exc:
        raise BuildError(f"{relative(path)}: file is not valid UTF-8") from exc
    if not source.strip():
        raise BuildError(f"{relative(path)}: the post is empty")

    match = POST_FILENAME_RE.match(path.name)
    if not match:
        raise BuildError(
            f"{relative(path)}: filename must look like 2026-10-19-my-post.md"
        )
    try:
        published = Date(
            int(match.group("year")),
            int(match.group("month")),
            int(match.group("day")),
        )
    except ValueError as exc:
        raise BuildError(f"{relative(path)}: invalid date in filename — {exc}") from exc

    metadata, source = parse_front_matter(source, path)
    title, body = extract_title(source, path)
    summary = extract_summary(body) or fallback_summary
    renderer = markdown.Markdown(extensions=["extra", "sane_lists"])
    content = renderer.convert(body)

    return Post(
        source=path,
        stem=path.stem,
        slug=match.group("slug"),
        published=published,
        title=title,
        summary=summary,
        content=content,
        author=metadata.get("author", ""),
        year=metadata.get("year", ""),
    )


def load_posts(config: dict[str, Any]) -> list[Post]:
    if not POSTS_DIR.is_dir():
        raise BuildError("posts/ directory is missing")
    paths = sorted(
        path
        for path in POSTS_DIR.glob("*.md")
        if path.is_file() and not path.name.startswith(".")
    )
    if not paths:
        raise BuildError("posts/ contains no .md files")

    posts = [load_post(path, config["description"]) for path in paths]
    posts.sort(key=lambda post: (post.published, post.stem))
    return posts


def render_template(template: str, values: dict[str, Any], name: str) -> str:
    missing: set[str] = set()

    def replace(match: re.Match[str]) -> str:
        key = match.group(1)
        if key not in values:
            missing.add(key)
            return match.group(0)
        return str(values[key])

    rendered = PLACEHOLDER_RE.sub(replace, template)
    if missing:
        raise BuildError(
            f"template {name} uses unknown placeholder(s): {', '.join(sorted(missing))}"
        )
    return rendered


def base_values(
    config: dict[str, Any],
    *,
    root: str,
    page_title: str,
    description: str,
    canonical: str,
    og_type: str = "website",
    article_meta: str = "",
    structured_data: str = "",
) -> dict[str, Any]:
    logo_rel = str(config.get("logo", "imgs/logo.png")).lstrip("/")
    logo_path = ROOT / logo_rel
    logo_url = root + logo_rel
    if logo_path.is_file():
        logo_url += f"?v={int(logo_path.stat().st_mtime)}"
    return {
        "lang": escape(config["language"], quote=False),
        "site_title": escape(config["title"]),
        "tagline": escape(config["tagline"], quote=False),
        "meta_author": escape(config["author"], quote=False),
        "footer_motto": escape(
            config.get("footer_motto", "求道之人，不问寒暑。"), quote=False
        ),
        "not_found_title": escape(
            config.get("not_found_title", "这条路径不存在。"), quote=False
        ),
        "not_found_body": escape(
            config.get("not_found_body", "页面可能已经被移走，或者还没有被写下。"),
            quote=False,
        ),
        "logo_url": escape(logo_url),
        "root": root,
        "css_href": root + "assets/css/style.css",
        "favicon_href": root + "assets/favicon.svg",
        "ico_href": root + "favicon.ico",
        "page_title": escape(page_title, quote=False),
        "meta_description": escape(description),
        "canonical": escape(canonical),
        "og_type": escape(og_type),
        "article_meta": article_meta,
        "structured_data": structured_data,
    }


def structured_data_for_post(post: Post, config: dict[str, Any], canonical: str) -> str:
    payload = {
        "@context": "https://schema.org",
        "@type": "BlogPosting",
        "headline": post.title,
        "description": post.summary,
        "datePublished": post.published.isoformat(),
        "dateModified": post.published.isoformat(),
        "inLanguage": config["language"],
        "author": {"@type": "Person", "name": post.author or config["author"]},
        "publisher": {"@type": "Person", "name": config["author"]},
        "mainEntityOfPage": {"@type": "WebPage", "@id": canonical},
    }
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    body = body.replace("<", "\\u003c")
    return f'<script type="application/ld+json">{body}</script>'


def build_post_index(posts: list[Post], root: str) -> str:
    rows: list[str] = []
    for post in reversed(posts):
        rows.append(
            f'<li><a href="{escape(root + post.url)}">'
            f'<time datetime="{post.published.isoformat()}">{post.date_display}</time>'
            f'<span class="post-index-title">{escape(post.title, quote=False)}</span>'
            "</a></li>"
        )
    return "\n".join(rows)


def render_index(config: dict[str, Any], posts: list[Post]) -> dict[str, Any]:
    root = "./"
    values = base_values(
        config,
        root=root,
        page_title=f'{config["title"]} — {config["tagline"]}',
        description=config["description"],
        canonical=f'{config["url"]}/',
    )
    values.update(
        {
            "content": "",
            "post_index": build_post_index(posts, root),
        }
    )
    return values


def render_post(config: dict[str, Any], post: Post) -> dict[str, Any]:
    root = "../"
    canonical = f'{config["url"]}/{post.url}'
    article_author = post.author or config["author"]
    article_meta = (
        f'<meta property="article:published_time" content="{post.published.isoformat()}">\n'
        f'  <meta property="article:author" content="{escape(article_author)}">'
    )
    values = base_values(
        config,
        root=root,
        page_title=f'{post.title} · {config["title"]}',
        description=post.summary,
        canonical=canonical,
        og_type="article",
        article_meta=article_meta,
        structured_data=structured_data_for_post(post, config, canonical),
    )
    values["meta_author"] = escape(post.author or config["author"], quote=False)
    values.update(
        {
            "content": "",
            "post_title": escape(post.title, quote=False),
            "post_byline": escape(post.byline, quote=False),
            "post_date": post.date_display,
            "post_date_iso": post.published.isoformat(),
            "prose": post.content,
        }
    )
    return values


def render_404(config: dict[str, Any]) -> dict[str, Any]:
    values = base_values(
        config,
        root="/",
        page_title=f'页面不存在 · {config["title"]}',
        description=(
            f'{config.get("not_found_title", "这条路径不存在。")} '
            f'{config.get("not_found_body", "页面可能已经被移走，或者还没有被写下。")}'
        ),
        canonical=f'{config["url"]}/404.html',
    )
    values["content"] = ""
    return values


def build(site_config: dict[str, Any] | None = None) -> list[Path]:
    started = time.perf_counter()
    config = site_config or load_config()

    template_names = ("base.html", "index.html", "post.html", "404.html")
    templates: dict[str, str] = {}
    for name in template_names:
        path = TEMPLATES_DIR / name
        if not path.is_file():
            raise BuildError(f"template is missing: {relative(path)}")
        templates[name] = path.read_text(encoding="utf-8")

    posts = load_posts(config)
    HTML_DIR.mkdir(parents=True, exist_ok=True)

    written: list[Path] = []

    index_values = render_index(config, posts)
    index_values["content"] = render_template(
        templates["index.html"], index_values, "index.html"
    )
    index_html = render_template(templates["base.html"], index_values, "base.html")
    index_path = ROOT / "index.html"
    write_file(index_path, index_html)
    written.append(index_path)

    expected_names: set[str] = set()
    for post in posts:
        post_values = render_post(config, post)
        post_values["content"] = render_template(
            templates["post.html"], post_values, "post.html"
        )
        post_html = render_template(templates["base.html"], post_values, "base.html")
        output = HTML_DIR / post.output_name
        write_file(output, post_html)
        written.append(output)
        expected_names.add(post.output_name)

    not_found_values = render_404(config)
    not_found_values["content"] = render_template(
        templates["404.html"], not_found_values, "404.html"
    )
    not_found_html = render_template(
        templates["base.html"], not_found_values, "base.html"
    )
    not_found_path = ROOT / "404.html"
    write_file(not_found_path, not_found_html)
    written.append(not_found_path)

    for existing in HTML_DIR.glob("*.html"):
        if existing.name in expected_names:
            continue
        try:
            text = existing.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        if GENERATED_MARKER in text:
            existing.unlink()
            print(f"removed stale page: {relative(existing)}")

    if not (ROOT / "assets/css/style.css").is_file():
        print("warning: assets/css/style.css is missing", file=sys.stderr)

    elapsed_ms = (time.perf_counter() - started) * 1000
    print(f"built {len(posts)} posts, {len(written)} pages in {elapsed_ms:.0f} ms")
    return written


def serve(port: int) -> None:
    build()
    handler = partial(SimpleHTTPRequestHandler, directory=str(ROOT))
    try:
        server = ThreadingHTTPServer(("127.0.0.1", port), handler)
    except OSError as exc:
        raise BuildError(f"could not start preview on port {port}: {exc}") from exc
    print(f"preview: http://127.0.0.1:{port}/  (Ctrl+C to stop)")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\npreview stopped")
    finally:
        server.server_close()


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build the blackball static blog.")
    parser.add_argument(
        "--serve",
        action="store_true",
        help="build, then serve the site at http://127.0.0.1:8000/",
    )
    parser.add_argument(
        "--port",
        type=int,
        default=8000,
        help="port for --serve (default: 8000)",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    try:
        if args.serve:
            serve(args.port)
        else:
            build()
    except BuildError as exc:
        print(f"build failed: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
